-- 2. TABEL PROFIL & PENGGUNA (SDD 5.2.1)
create table if not exists public.app_user (
  user_id bigint generated by default as identity primary key,
  auth_uid uuid unique references auth.users (id) on delete cascade,
  username varchar(50) unique not null,
  display_name varchar(100) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Tabel preferensi aksesibilitas pasien (UI WCAG 2.1)
create table if not exists public.user_preferences (
  user_id uuid primary key references auth.users (id) on delete cascade,
  text_size text not null default 'standard'
    check (text_size in ('standard', 'large', 'extra_large')),
  high_contrast boolean not null default true,
  reminders_enabled boolean not null default false,
  audio_guidance_enabled boolean not null default true,
  visual_cues_enabled boolean not null default true,
  updated_at timestamptz not null default now()
);

-- View profiles untuk kompatibilitas frontend lama
create or replace view public.profiles as
  select 
    u.auth_uid as id,
    u.display_name,
    u.created_at,
    u.updated_at
  from public.app_user u;

-- 3. TABEL PERANGKAT STEPPING GRID (SDD 5.2.2)
create table if not exists public.device (
  device_id bigint generated by default as identity primary key,
  device_code varchar(50) unique not null,
  device_name varchar(100),
  connection_type varchar(20) not null default 'wifi',
  status varchar(20) not null default 'offline' check (status in ('online', 'offline', 'error')),
  firmware_version varchar(20) default '1.0.0',
  last_calibrated_at timestamptz,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- View matras_devices untuk kompatibilitas
create or replace view public.matras_devices as
  select
    d.device_id::text as id,
    null::uuid as user_id,
    d.device_code as device_identifier,
    d.device_name as display_label,
    d.created_at,
    d.updated_at
  from public.device d;

-- 4. TABEL MODE LATIHAN (SDD 5.2.3)
create table if not exists public.training_mode (
  mode_id smallint primary key,
  mode_name varchar(50) unique not null,
  description text,
  is_active boolean not null default true
);

-- 5. TABEL LAYOUT UBIN MODULAR (SDD 5.2.4)
create table if not exists public.layout (
  layout_id smallint primary key,
  layout_code varchar(20) unique not null,
  layout_name varchar(50) not null,
  tile_count smallint not null check (tile_count between 1 and 4),
  start_positions jsonb not null,
  sequential_pattern jsonb not null,
  is_active boolean not null default true
);

-- 6. TABEL MASTER POSISI UBIN (SDD 5.2.5)
create table if not exists public.tile_position (
  position_id smallint primary key,
  layout_id smallint not null references public.layout (layout_id) on delete cascade,
  position_code varchar(5) not null,
  position_label varchar(30) not null,
  port_number smallint not null check (port_number between 1 and 4),
  side char(1) not null check (side in ('L', 'C', 'R')),
  grid_x smallint not null,
  grid_y smallint not null,
  unique (layout_id, position_code),
  unique (layout_id, port_number)
);

-- 7. TABEL SESI LATIHAN (SDD 5.2.6)
create table if not exists public.training_session (
  session_id bigint generated by default as identity primary key,
  user_id bigint not null references public.app_user (user_id) on delete cascade,
  device_id bigint not null references public.device (device_id) on delete cascade,
  mode_id smallint not null references public.training_mode (mode_id),
  session_status varchar(20) not null default 'waiting' 
    check (session_status in ('waiting', 'running', 'stopped', 'completed')),
  started_at timestamptz,
  ended_at timestamptz,
  created_at timestamptz not null default now()
);

-- Indeks unik parsial agar hanya ada satu sesi aktif (waiting / running) per user dan per device
create unique index if not exists idx_unique_active_user_session 
  on public.training_session (user_id) 
  where session_status in ('waiting', 'running');

create unique index if not exists idx_unique_active_device_session 
  on public.training_session (device_id) 
  where session_status in ('waiting', 'running');

create index if not exists idx_training_session_user_started 
  on public.training_session (user_id, started_at desc nulls last);

