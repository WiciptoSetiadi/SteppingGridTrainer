-- Trigger pembuatan profil pengguna otomatis saat signup di Supabase Auth
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username varchar(50);
  v_display_name varchar(100);
begin
  v_username := coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1));
  v_display_name := coalesce(new.raw_user_meta_data->>'display_name', new.raw_user_meta_data->>'full_name', v_username);

  insert into public.app_user (auth_uid, username, display_name)
  values (new.id, v_username, v_display_name)
  on conflict (auth_uid) do update set
    display_name = coalesce(excluded.display_name, app_user.display_name);

  insert into public.user_preferences (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- RPC: Buat sesi latihan dan konfigurasi dalam 1 transaksi (SDD Appendix B)
create or replace function public.create_session(
  p_device_id bigint,
  p_mode_id smallint,
  p_layout_id smallint,
  p_target_tempo_ms int,
  p_step_timeout_ms int default 10000,
  p_total_targets int default 20,
  p_mode_parameters jsonb default '{}'::jsonb
) returns bigint
language plpgsql
security definer
as $$
declare
  v_user_id bigint;
  v_session_id bigint;
begin
  -- Temukan user_id dari auth.uid()
  select user_id into v_user_id from public.app_user where auth_uid = auth.uid();
  if v_user_id is null then
    raise exception 'User profile not found for authenticated user %', auth.uid();
  end if;

  -- Buat baris training_session
  insert into public.training_session (
    user_id,
    device_id,
    mode_id,
    session_status,
    created_at
  ) values (
    v_user_id,
    p_device_id,
    p_mode_id,
    'waiting',
    now()
  ) returning session_id into v_session_id;

  -- Buat baris session_config
  insert into public.session_config (
    session_id,
    layout_id,
    target_tempo_ms,
    step_timeout_ms,
    total_targets,
    mode_parameters
  ) values (
    v_session_id,
    p_layout_id,
    p_target_tempo_ms,
    coalesce(p_step_timeout_ms, 10000),
    coalesce(p_total_targets, 20),
    coalesce(p_mode_parameters, '{}'::jsonb)
  );

  return v_session_id;
end;
$$;

