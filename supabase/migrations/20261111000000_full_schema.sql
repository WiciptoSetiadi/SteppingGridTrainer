    status = coalesce(p_status, 'online'),
    firmware_version = coalesce(p_firmware_version, firmware_version),
    updated_at = now()
  where device_code = p_device_code;
  
  return found;
end;
$$;

-- RPC: Ringkasan progres harian pasien (SDD 3.2.7)
create or replace function public.get_daily_summary(p_user_id bigint)
returns jsonb
language plpgsql
security definer
as $$
declare
  v_total_sessions int;
  v_avg_accuracy numeric(5,2);
  v_recent_accuracy numeric(5,2);
begin
  select count(*), coalesce(avg(r.accuracy_percent), 0)
  into v_total_sessions, v_avg_accuracy
  from public.training_session s
  join public.session_result r on s.session_id = r.session_id
  where s.user_id = p_user_id and s.session_status = 'completed';

  select r.accuracy_percent into v_recent_accuracy
  from public.training_session s
  join public.session_result r on s.session_id = r.session_id
  where s.user_id = p_user_id and s.session_status = 'completed'
  order by s.created_at desc limit 1;

  return jsonb_build_object(
    'total_sessions', v_total_sessions,
    'average_accuracy', round(v_avg_accuracy, 1),
    'recent_accuracy', coalesce(v_recent_accuracy, 0.0)
  );
end;
$$;

